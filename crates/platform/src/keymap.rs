fn forward(table: &[(u16, u16)], hid: HidUsage) -> Option<u16> {
    table.iter().find(|(h, _)| *h == hid.0).map(|(_, c)| *c)
}

fn backward(table: &[(u16, u16)], code: u16) -> Option<HidUsage> {
    table
        .iter()
        .find(|(_, c)| *c == code)
        .map(|(h, _)| HidUsage(*h))
}

/// HID usage → set 1 scan code (with `0xE0` in the high byte for extended keys).
pub fn hid_to_set1(hid: HidUsage) -> Option<u16> {
    forward(SET1, hid)
}

pub fn set1_to_hid(scan: u16) -> Option<HidUsage> {
    backward(SET1, scan)
}

pub fn hid_to_evdev(hid: HidUsage) -> Option<u16> {
    forward(EVDEV, hid)
}

pub fn evdev_to_hid(code: u16) -> Option<HidUsage> {
    backward(EVDEV, code)
}

pub fn hid_to_mac(hid: HidUsage) -> Option<u16> {
    forward(MAC, hid)
}

pub fn mac_to_hid(code: u16) -> Option<HidUsage> {
    backward(MAC, code)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn tables_are_bijective_and_round_trip() {
        for (h, _) in MAC {
            let hid = HidUsage(*h);
            assert_eq!(mac_to_hid(hid_to_mac(hid).unwrap()), Some(hid));
        }
        assert_eq!(hid_to_mac(HidUsage::A), Some(0x00));
        assert_eq!(hid_to_mac(HidUsage::LEFT_GUI), Some(0x37), "Command");
        for table in [SET1, EVDEV, MAC] {
            let hids: HashSet<u16> = table.iter().map(|(h, _)| *h).collect();
            let codes: HashSet<u16> = table.iter().map(|(_, c)| *c).collect();
            assert_eq!(hids.len(), table.len(), "duplicate HID usage");
            assert_eq!(codes.len(), table.len(), "duplicate OS code");
        }
        for (h, _) in SET1 {
            let hid = HidUsage(*h);
            assert_eq!(set1_to_hid(hid_to_set1(hid).unwrap()), Some(hid));
        }
        for (h, _) in EVDEV {
            let hid = HidUsage(*h);
            assert_eq!(evdev_to_hid(hid_to_evdev(hid).unwrap()), Some(hid));
        }
    }

    #[test]
    fn well_known_keys() {
        assert_eq!(hid_to_set1(HidUsage::A), Some(0x1E));
        assert_eq!(hid_to_set1(HidUsage::RIGHT_CTRL), Some(0xE01D));
        assert_eq!(hid_to_set1(HidUsage::LEFT_GUI), Some(0xE05B));
        assert_eq!(hid_to_evdev(HidUsage::A), Some(30));
        assert_eq!(hid_to_evdev(HidUsage::ESCAPE), Some(1));
        assert_eq!(evdev_to_hid(125), Some(HidUsage::LEFT_GUI));
        // Every letter, digit and modifier is covered on both tables.
        for u in (0x04..=0x27).chain(0xE0..=0xE7) {
            assert!(hid_to_set1(HidUsage(u)).is_some(), "set1 {u:#x}");
            assert!(hid_to_evdev(HidUsage(u)).is_some(), "evdev {u:#x}");
        }
        assert_eq!(hid_to_set1(HidUsage(0xFF)), None);
    }
}
